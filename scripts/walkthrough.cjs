// A real 30+ second browser recording demonstrates navigation and a sample local-only enquiry.
const { chromium } = require('C:/Users/DE LL/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright')
const fs = require('node:fs/promises')
;(async () => {
  const browser = await chromium.launch({ headless: true, channel: 'msedge' })
  const context = await browser.newContext({ viewport: { width: 1440, height: 900 }, recordVideo: { dir: 'tmp/recordings', size: { width: 1440, height: 900 } } })
  const page = await context.newPage()
  const origin = process.argv[2] || 'http://127.0.0.1:4188'
  await page.goto(origin, { waitUntil: 'networkidle' }); await page.waitForTimeout(4500)
  await page.locator('#programs').scrollIntoViewIfNeeded(); await page.waitForTimeout(3500)
  await page.goto(origin + '/programs', { waitUntil: 'networkidle' }); await page.waitForTimeout(3000)
  await page.getByRole('button', { name: 'Strength', exact: true }).click(); await page.waitForTimeout(2500)
  await page.getByRole('link', { name: 'Strength Foundations', exact: true }).click(); await page.waitForTimeout(3500)
  await page.getByRole('link', { name: 'Explore this program', exact: true }).click(); await page.waitForTimeout(3000)
  await page.getByLabel('Your name *').fill('Alex Sample')
  await page.getByLabel('Email address *').fill('alex@example.com')
  await page.getByLabel('A general fitness goal *').fill('Build a consistent training routine.')
  await page.getByRole('checkbox').check(); await page.waitForTimeout(2500)
  await page.getByRole('button', { name: 'Try the demo enquiry' }).click(); await page.waitForTimeout(4000)
  await page.goto(origin + '/faq', { waitUntil: 'networkidle' })
  await page.getByRole('button', { name: 'Are the prices and stories real?' }).click(); await page.waitForTimeout(4000)
  const video = page.video()
  await context.close()
  await fs.mkdir('docs/walkthrough', { recursive: true })
  await video.saveAs('docs/walkthrough/elevate-performance-coaching.webm')
  await browser.close()
  console.log('Saved actual browser walkthrough to docs/walkthrough/elevate-performance-coaching.webm')
})().catch(error => { console.error(error); process.exitCode = 1 })
